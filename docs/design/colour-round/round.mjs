/**
 * Colour round tooling (docs/PLAN-CURRENT.md section 4, step C0). Pictures and a
 * contrast table only: nothing here changes the site.
 *
 *   node docs/design/colour-round/round.mjs css        write candidate-<id>.css
 *   node docs/design/colour-round/round.mjs contrast   print the contrast table (Markdown)
 *   node docs/design/colour-round/round.mjs capture    capture the reference pages (OUT, BASE_URL)
 *   node docs/design/colour-round/round.mjs sheets     build the contact sheets from OUT
 *
 * Run from a checkout that has node_modules (Playwright is resolved from the
 * current directory). BASE_URL defaults to the live site, read only; the
 * candidate CSS is injected into the loaded page, so no build is needed.
 */
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { palettes, pages } from "./palettes.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(process.env.OUT ?? join(HERE, ".captures"));
const BASE = (process.env.BASE_URL ?? "https://ukcounciltax.co.uk").replace(/\/$/, "");
const THEMES = ["dark", "light"];
const VIEWS = [{ id: "1440", width: 1440, height: 900 }, { id: "390", width: 390, height: 844 }];
const candidates = Object.keys(palettes).filter((id) => id !== "live");

/* ---------- css ---------- */

function block(set) {
  const lines = Object.entries(set).filter(([k]) => k !== "desk").map(([k, v]) => `  --${k}: ${v};`);
  lines.push(`  --round-desk: ${set.desk};`);
  return lines.join("\n");
}

export function cssFor(id) {
  const p = palettes[id];
  return [
    `/* Colour round candidate: ${p.name}. For pictures only. Generated by round.mjs from palettes.mjs. */`,
    `:root, [data-theme="light"] {\n${block(p.light)}\n}`,
    `:root[data-theme="dark"], [data-theme="dark"] {\n${block(p.dark)}\n}`,
    `@media (prefers-color-scheme: dark) {\n:root:not([data-theme="light"]) {\n${block(p.dark)}\n}\n}`,
    `.desk { --desk-ground: var(--round-desk); }`,
    "",
  ].join("\n\n");
}

/* ---------- contrast (WCAG 2 relative luminance) ---------- */

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const hexOf = (c) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
/** `a` at `t` (0 to 1) over `b`, in sRGB, as the browser's color-mix(in srgb) does. */
export const over = (a, b, t) => hexOf(rgb(a).map((v, i) => v * t + rgb(b)[i] * (1 - t)));
const lum = (hex) => {
  const [r, g, b] = rgb(hex).map((v) => { const s = v / 255; return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };

/** Every pair the round holds a candidate to: [label, foreground, background, floor]. */
