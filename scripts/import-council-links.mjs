import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
const file = process.argv[2];
if (!file) throw new Error('Supply the pinned UK Places local links file path');
const raw = readFileSync(file);
const sha256 = createHash('sha256').update(raw).digest('hex');
if (sha256 !== '085eb3b0511aca0f3fad79a9aa3f0decd5a7b5529240229ceed7731b3fb0b617') throw new Error('A3 stop: UK Places source hash differs');
const data = JSON.parse(raw);
const links = Object.fromEntries(Object.entries(data.places).filter(([gss, place]) => /^[ESW]/.test(gss) && place.links.councilTax).map(([gss, place]) => [gss, {councilTax: place.links.councilTax}]));
if (Object.keys(links).length !== 316) throw new Error('A3 stop: expected 316 council tax links');
const service = data.services.find(service => service.id === 'councilTax');
const source = {...data.source, checkedOn: data.checkedOn, checkedBy: 'UK Places', service: {title: service.title, lgsl: service.lgsl, lgil: service.lgil}, via: {file: 'src/data/local-links.json', commit: '2bea52dbe74c7a689a500b3b73ff63dcefb900b6', sha256}};
writeFileSync(join(process.cwd(), 'data/council-links.json'), JSON.stringify({source, links}, null, 2) + '\n');
console.log(`Imported ${Object.keys(links).length} pinned council tax links`);
